const module = new vm.SourceTextModule(source + '\nglobalThis.test = {copyOutputFolder, getState};', { context });
await module.link(() => app); await module.evaluate();
const node = { properties: {}, setDirtyCanvas() {} };
context.test.getState(node).outputFolder = '/output/folder with spaces';
await context.test.copyOutputFolder(node);
assert.deepEqual(copied, ['/output/folder with spaces']);
assert.equal(node._kooFinisherStatus, 'Output path copied');
