def _merge_unique(groups, mapping_name):
    merged = {}
    for group in groups:
        for key, value in group.items():
            if key in merged:
                raise RuntimeError(f"Duplicate KoO {mapping_name} identifier in release package: {key}")
            merged[key] = value
    return merged


